const STORAGE_PREFIX = "planora.plan_hint_hidden.";

/**
 * Закрыта ли подсказка про относительный план — по проекту, в браузере.
 *
 * Подсказка объясняет, что делать с планом без дат, и первому, кто открыл
 * такой проект, нужна. Прочитанная, она остаётся стоять полосой в полсотни
 * пикселей над каждым открытием ленты и повторяет то, что рядом уже говорит
 * плашка «Относительный план» в тулбаре, — поэтому её можно закрыть.
 *
 * В браузере, а не на сервере: это не свойство проекта, а состояние одного
 * читателя, и вернуть подсказку соседу по организации закрытие не должно.
 * Ключ с проектом внутри — по той же причине, что у масштаба ленты (см.
 * scalePreference): закрытая в одном проекте подсказка не отвечает за другой,
 * где план тоже относительный, а человек там впервые.
 *
 * Приватный режим браузера умеет запрещать localStorage — тогда подсказка
 * просто вернётся в следующий раз. Это не повод падать (см. storedZoom).
 */
export function planHintHidden(projectId: string): boolean {
  try {
    return localStorage.getItem(STORAGE_PREFIX + projectId) === "1";
  } catch {
    return false;
  }
}

export function hidePlanHint(projectId: string): void {
  try {
    localStorage.setItem(STORAGE_PREFIX + projectId, "1");
  } catch {
    // см. planHintHidden()
  }
}
