import { useCallback, useEffect, useLayoutEffect } from "react";
import type { RefObject } from "react";

/**
 * Высота прокручиваемой части ленты — по остатку окна под её верхним краем.
 *
 * Шапка шкалы объявлена `position: sticky; top: 0` (см. `.gantt__head-row`),
 * но закрепляться ей было негде. У `.gantt__scroll` задан только
 * `overflow-x`, высота не ограничена ничем — контейнер вырастает во всю высоту
 * содержимого и вертикально не прокручивается никогда. Вертикально едет
 * страница, и шапка уезжает вместе с ней: месяцы, недели и числа пропадают
 * ровно тогда, когда по ним и сверяются — когда задач больше, чем помещается в
 * окно. На проекте в десяток строк этого не видно (лента и так короче окна), и
 * поэтому оно и держалось так долго.
 *
 * Правится не разметкой шапки, а высотой ленты: `sticky` закрепляется внутри
 * ближайшего прокручиваемого предка, и предок обязан прокручиваться сам. Тем
 * же чинится и вторая половина обещания из `gantt.css` («прокручивается лента,
 * а не страница») — по горизонтали оно выполнялось всегда, по вертикали не
 * выполнялось вовсе.
 *
 * Числом, а не `max-height: 100dvh` в стилях: над лентой стоит шапка проекта
 * с вкладками и тулбар, и вычесть их высоту стили не могут — она разная и на
 * разных экранах, и по ходу работы (строка шапки и тулбар переносят содержимое
 * в узком окне, над лентой появляется предложение подвинуть связанную задачу,
 * закрывается подсказка про относительный план).
 *
 * Отдельной подписки на эти перемены не нужно: всё, что меняет высоту над
 * лентой, — перерисовка экрана проекта, а с ней перерисовывается и лента (см.
 * useLayoutEffect ниже — он без списка зависимостей). Подписка на
 * `transitionend` здесь стояла ради складывающейся шапки, которой больше нет.
 */

/**
 * Ниже этого лента перестаёт быть лентой. Упор нужен для окна, в котором на
 * ленту не остаётся места вовсе (телефон в альбомной ориентации, длинная шапка
 * проекта): лучше отдать странице прокрутку и показать хотя бы несколько
 * строк, чем схлопнуть ленту в полосу.
 */
const MIN_HEIGHT = 240;

export function useViewportFit(box: RefObject<HTMLElement | null>): void {
  const fit = useCallback(() => {
    const node = box.current;
    if (node === null) return;

    const bounds = node.getBoundingClientRect();
    // Место ленты на странице, а не в окне: считать от текущего положения
    // прокрутки значило бы менять высоту на каждый оборот колеса.
    const top = bounds.top + window.scrollY;
    // Всё, что стоит в ленте ниже прокручиваемой части, — сноска под шкалой.
    // Без этой поправки страница получала бы на её высоту собственную
    // прокрутку, и закреплённая шапка уезжала бы вместе со страницей — то
    // самое, от чего здесь и уходят, только на десяток пикселей.
    const root = node.closest<HTMLElement>(".gantt");
    const below = root === null ? 0 : root.getBoundingClientRect().bottom - bounds.bottom;

    const height = Math.max(MIN_HEIGHT, Math.round(window.innerHeight - top - below));
    const next = `${height}px`;
    // Только при изменении: запись в стиль — это пересчёт разметки, а мерить
    // приходится на каждую отрисовку ленты.
    if (node.style.maxHeight !== next) node.style.maxHeight = next;
  }, [box]);

  // Без списка зависимостей — на каждую отрисовку ленты: высота того, что над
  // ней, меняется не только от размера окна (тулбар переносит кнопки, над
  // лентой появляется предложение подвинуть связанную задачу), а лента и так
  // отрисовывается на всякую правку плана. Обе меры — это один принудительный
  // пересчёт разметки: вторая читает уже пересчитанное. Подписка на размеры
  // (`ResizeObserver`) стоила бы полифила ради jsdom и всё равно не увидела бы
  // соседей ленты — они живут выше неё, в экране проекта.
  //
  // Слоем разметки, а не эффектом: кадр с невыставленной высотой был бы
  // виден — лента на нём растянута во всю страницу.
  useLayoutEffect(fit);

  useEffect(() => {
    window.addEventListener("resize", fit);
    return () => window.removeEventListener("resize", fit);
  }, [fit]);
}
